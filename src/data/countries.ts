// Helper functions for team management
export const getTeamByCountryCode = (code: string): CountryInfo | undefined => {
  return countries.find(country => country.code === code);
};
export const getTeamByAlpha2Code = (code: string): CountryInfo | undefined => {
  return countries.find(country => country.alpha2 === code);
};
export const getTeamByAlpha3Code = (code: string): CountryInfo | undefined => {
  return countries.find(country => country.alpha3 === code);
};

export const searchTeams = (query: string): CountryInfo[] => {
  const searchTerm = query.toLowerCase().trim();
  if (!searchTerm) return countries;
  
  return countries.filter(country =>
    country.name.toLowerCase().includes(searchTerm) ||
    country.code.toLowerCase().includes(searchTerm)
  );
};
